#!/usr/bin/env python3
"""Convert a PSF2 console font to a C header with ASCII 32..126 glyphs, plus the degree sign
(U+00B0) at code 127, written as "\x7f" in strings.

Usage: psf2c.py <font.psf[.gz]> <out.h>
Glyphs are looked up through the font's Unicode table when it has one.
"""
import gzip, struct, sys

def main():
    src, out = sys.argv[1], sys.argv[2]
    data = (gzip.open if src.endswith('.gz') else open)(src, 'rb').read()
    magic, ver, hdr, flags, n, gsize, h, w = struct.unpack_from('<8I', data)
    assert magic == 0x864ab572, 'not PSF2'
    glyphs = data[hdr:hdr + n * gsize]
    index = {cp: cp for cp in range(n)}
    if flags & 1:                                   # unicode table follows the glyphs
        table, gi, pos = data[hdr + n * gsize:], 0, 0
        index = {}
        while gi < n and pos < len(table):
            end = table.index(b'\xff', pos)
            for chunk in table[pos:end].split(b'\xfe')[:1]:
                for ch in chunk.decode('utf-8', 'ignore'):
                    index.setdefault(ord(ch), gi)
            pos, gi = end + 1, gi + 1
    row_bytes = (w + 7) // 8
    lines = [f'/* Generated by tools/psf2c.py from {src.split("/")[-1]} (Terminus, SIL OFL 1.1). */',
             '#ifndef CAMAPP_FONT_H', '#define CAMAPP_FONT_H', '#include <stdint.h>',
             f'#define FONT_W {w}', f'#define FONT_H {h}', f'#define FONT_ROW_BYTES {row_bytes}',
             '#define FONT_FIRST 32', '#define FONT_LAST 127',
             f'static const uint8_t font_glyphs[96][{h * row_bytes}] = {{']
    for code in range(32, 128):
        cp = 0xb0 if code == 127 else code          # 127: degree sign
        g = glyphs[index.get(cp, index.get(ord('?'))) * gsize:][:h * row_bytes]
        lines.append('    { ' + ', '.join(f'0x{b:02x}' for b in g) + f' }}, /* {chr(cp)!r} */')
    lines += ['};', '#endif', '']
    open(out, 'w').write('\n'.join(lines))
    print(f'{out}: {w}x{h}, {n} glyphs in font, 96 exported')

if __name__ == '__main__':
    main()
